// -------------------------------------------------------------------------
// F103 MEASURE_RAW (v5) — «выстрел и всё сразу»: запрос как у F102
// (usfmCmdMeasure), ответ ОДНИМ кадром:
//   [addr][103][usfmMeasureReply][UPS: sample_size*2 байт]
//                                [DNS: sample_size*2 байт][crc]
// Выборки int16 LE, количество на направление — из reply.sample_size
// этого же кадра (при BADPARAM оно 0 и данных нет). Одна транзакция
// вместо трёх-четырёх — экономит и время тишины-кадрирования, и байты
// заголовков; на 250 кбод кадр 216 выборок уходит ~40 мс.
// Ошибки — обычным исключением [addr][103|0x80][код][crc].

// -------------------------------------------------------------------------
// Смена скорости порта (v5): запись baud в блок 300 применяется сразу
// (ответ-квитанция уходит ещё на старой скорости), но со страховкой:
// если на НОВОЙ скорости за USFM_BAUD_PROBATION_S секунд не пришло ни
// одного валидного адресованного кадра — прибор сам откатывается на
// прежнюю скорость. Лесенку скоростей можно щупать без риска потерять
// связь: не получилось — подождал 5 секунд и продолжил на старой.
#define USFM_BAUD_PROBATION_S   (5)

